"""Compact live pane: persistent manual actions, corner crop, and bottom snapshot."""
from PySide6.QtCore import Qt
from PySide6.QtGui import QAction
from PySide6.QtWidgets import (
    QComboBox, QDialog, QFrame, QHBoxLayout, QLabel, QMenu, QPushButton,
    QSizePolicy, QSlider, QToolButton, QVBoxLayout,
)
from .presentation import label_for
from .video import VideoCanvas


def build_live_pane(self, slot_title):
    outer = QVBoxLayout(self)
    outer.setContentsMargins(3, 3, 3, 3)
    outer.setSpacing(3)
    heading = QHBoxLayout()
    heading.setSpacing(4)
    self.view_title = QLabel(slot_title)
    self.view_title.setStyleSheet("font-weight:700")
    self.view_title.setVisible(False)
    self.picker = QComboBox()
    self.picker.setAccessibleName(f"{slot_title} camera")
    self.picker.setSizePolicy(QSizePolicy.Policy.Ignored, QSizePolicy.Policy.Fixed)
    self.picker.addItem("Choose camera…", None)
    self.picker.currentIndexChanged.connect(self._picked)
    self.picker.activated.connect(lambda *_: self.armed.emit(self))
    heading.addWidget(self.picker, 1)
    self.open_btn = QPushButton("Open (F8)")
    self.open_btn.setAccessibleName(f"{slot_title} manual open")
    self.open_btn.setProperty("compact", True)
    self.open_btn.clicked.connect(self.open_this_side)
    self.close_btn = QPushButton("Close (F9)")
    self.close_btn.setAccessibleName(f"{slot_title} manual close")
    self.close_btn.setProperty("compact", True)
    self.close_btn.clicked.connect(self.close_this_side)
    heading.addWidget(self.open_btn)
    heading.addWidget(self.close_btn)
    self.video_options = QToolButton()
    self.video_options.setText("⋮")
    self.video_options.setAccessibleName(f"{slot_title} video options")
    self.video_options.setPopupMode(QToolButton.ToolButtonPopupMode.InstantPopup)
    options = QMenu(self.video_options)
    self.fill_toggle = QAction("Fill view (crop edges)", options)
    self.fill_toggle.setCheckable(True)
    self.overlays_toggle = QAction("Detection overlays", options)
    self.overlays_toggle.setCheckable(True)
    options.addAction(self.fill_toggle)
    options.addAction(self.overlays_toggle)
    self.video_options.setMenu(options)
    heading.addWidget(self.video_options)
    outer.addLayout(heading)

    self.video = VideoCanvas("Choose a camera above")
    self.video.setObjectName("video")
    self.video.setAccessibleName(f"{slot_title} live picture")
    self.video.setAccessibleDescription("Live video. Press 1 or 2 to select a side for a confirmed manual gate command.")
    self.video.setAlignment(Qt.AlignmentFlag.AlignCenter)
    self.video.setMinimumHeight(180)
    self.fill_toggle.toggled.connect(self.video.set_fill_view)
    self.video.clicked.connect(self._on_video)
    self.video.pressed.connect(self._zone_press)
    self.video.moved.connect(self._zone_move)
    self.video.released.connect(self._zone_release)
    outer.addWidget(self.video, 1)

    self.crop_panel = QFrame()
    self.crop_panel.setObjectName("plateEvidence")
    crop_layout = QVBoxLayout(self.crop_panel)
    crop_layout.setContentsMargins(3, 2, 3, 3)
    crop_layout.setSpacing(1)
    crop_caption = QLabel("PLATE CROP")
    crop_caption.setStyleSheet("color:#dce6ef;font-weight:600;font-size:10px")
    crop_layout.addWidget(crop_caption)
    self.crop = VideoCanvas("Waiting for plate")
    self.crop.setObjectName("video")
    self.crop.setAccessibleName(f"{slot_title} last plate crop")
    self.crop.setFocusPolicy(Qt.FocusPolicy.NoFocus)
    self.crop.setAlignment(Qt.AlignmentFlag.AlignCenter)
    crop_layout.addWidget(self.crop, 1)
    self.video.set_corner_widget(self.crop_panel)

    footer = QHBoxLayout()
    footer.setSpacing(6)
    reading = QVBoxLayout()
    reading.setSpacing(1)
    self.plate = QLabel("—")
    self.plate.setStyleSheet("font-size:18px;font-weight:700;letter-spacing:2px")
    reading.addWidget(self.plate)
    self.details = QLabel("Waiting for a vehicle")
    self.details.setWordWrap(True)
    self.details.setMaximumHeight(34)
    reading.addWidget(self.details)
    self.decision = QLabel("")
    self.decision.setWordWrap(True)
    reading.addWidget(self.decision)
    footer.addLayout(reading, 1)
    snapshot_column = QVBoxLayout()
    snapshot_column.setSpacing(1)
    snapshot_caption = QLabel("LAST SNAPSHOT")
    snapshot_caption.setAlignment(Qt.AlignmentFlag.AlignCenter)
    snapshot_column.addWidget(snapshot_caption)
    self.last_snap = VideoCanvas("Waiting for vehicle")
    self.last_snap.setObjectName("video")
    self.last_snap.setAccessibleName(f"{slot_title} last vehicle snapshot")
    self.last_snap.setFocusPolicy(Qt.FocusPolicy.NoFocus)
    self.last_snap.setAlignment(Qt.AlignmentFlag.AlignCenter)
    self.last_snap.setFixedHeight(72)
    self.last_snap.setMinimumWidth(100)
    self.last_snap.setMaximumWidth(220)
    snapshot_column.addWidget(self.last_snap)
    footer.addLayout(snapshot_column, 1)
    review = QVBoxLayout()
    review.setSpacing(1)
    self.correct_btn = QPushButton("Correct plate")
    self.correct_btn.setProperty("compact", True)
    self.correct_btn.clicked.connect(self.correct_plate)
    review.addWidget(self.correct_btn)
    self.hold_label = QLabel("")
    self.hold_label.setWordWrap(True)
    self.hold_label.setMaximumWidth(150)
    review.addWidget(self.hold_label)
    self.target_chip = QLabel("")
    self.target_chip.setWordWrap(True)
    self.target_chip.setMaximumWidth(150)
    review.addWidget(self.target_chip)
    footer.addLayout(review, 1)
    outer.addLayout(footer)
    self.status = QLabel("No camera selected")
    self.status.setWordWrap(True)
    self.status.setMaximumHeight(32)
    outer.addWidget(self.status)

    self.zone_dialog = QDialog(self)
    self.zone_dialog.setWindowTitle(f"{slot_title} detection zone")
    zone_layout = QVBoxLayout(self.zone_dialog)
    zone_layout.addWidget(QLabel("Draw the detection zone on the live picture, then save."))
    self.zone_btn = QPushButton("Set detection zone")
    self.zone_btn.clicked.connect(self._toggle_zone)
    zone_layout.addWidget(self.zone_btn)
    self.zoom_label = QLabel("Zoom 1.0")
    self.zoom = QSlider(Qt.Orientation.Horizontal)
    self.zoom.setAccessibleName(f"{slot_title} detection zone zoom")
    self.zoom.setRange(10, 40)
    self.zoom.setValue(10)
    self.zoom.valueChanged.connect(self._zoom_changed)
    zone_layout.addWidget(label_for("Detection zoom", self.zoom))
    self.zoom.setAccessibleName(f"{slot_title} detection zone zoom")
    zone_layout.addWidget(self.zoom_label)
    zone_layout.addWidget(self.zoom)
    self.zone_save = QPushButton("Save zone")
    self.zone_save.clicked.connect(self._save_zone)
    zone_layout.addWidget(self.zone_save)
    zone_action = options.addAction("Detection zone…")
    zone_action.triggered.connect(self.zone_dialog.show)
    self.overlays_toggle.toggled.connect(
        lambda _: self._set_pixmap(self.video, self._last_jpeg, self._last_overlay) if self._last_jpeg else None
    )
